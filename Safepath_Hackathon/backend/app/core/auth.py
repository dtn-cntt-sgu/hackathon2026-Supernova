"""
Server-side Authentication & Session Token Verification for SafePathAI (B02, R14).

Enforces strict ownership and prevents IDOR / header spoofing on `/api/v1/user/*` endpoints:
- Issues HMAC-SHA256 signed session tokens bound to internal `user.id`, `email`, and `provider_account_id`.
- Verifies `Authorization: Bearer <token>` or signed `X-User-Token` headers.
- Rejects cross-user access (`403 FORBIDDEN`) when a valid token for User A attempts to access User B.
- Rejects unauthenticated or forged requests (`401 UNAUTHORIZED`).
"""

import base64
from datetime import datetime, timezone
import hashlib
import hmac
import json
from typing import Any, Dict, Optional

from backend.app.core.config import settings


def _get_signing_secret() -> bytes:
    return settings.AUTH_SECRET.encode("utf-8")


def create_user_session_token(
    user_id: str,
    email: str,
    provider_account_id: Optional[str] = None,
    ttl_seconds: int = 86400 * 7,
) -> str:
    """
    Creates an HMAC-SHA256 signed token containing user identity and expiration.
    Format: base64url(payload_json).hex_signature
    """
    now_ts = int(datetime.now(timezone.utc).timestamp())
    payload = {
        "iss": "safepath",
        "aud": "safepath-api",
        "sub": str(user_id),
        "email": str(email).lower().strip(),
        "pid": str(provider_account_id or ""),
        "iat": now_ts,
        "exp": now_ts + int(ttl_seconds),
    }
    raw_json = json.dumps(payload, separators=(",", ":"), sort_keys=True).encode("utf-8")
    b64_payload = base64.urlsafe_b64encode(raw_json).decode("ascii").rstrip("=")
    sig = hmac.new(_get_signing_secret(), b64_payload.encode("ascii"), hashlib.sha256).hexdigest()
    return f"{b64_payload}.{sig}"


def verify_user_session_token(token: Optional[str]) -> Optional[Dict[str, Any]]:
    """
    Verifies an HMAC-SHA256 signed user session token.
    Returns the decoded payload dict if valid and unexpired, or None otherwise.
    """
    if not token or not isinstance(token, str) or len(token) > 8192 or not token.isascii() or "." not in token:
        return None
    raw_token = token.strip()
    if raw_token.lower().startswith("bearer "):
        raw_token = raw_token[7:].strip()
    parts = raw_token.split(".")
    if len(parts) != 2:
        return None
    b64_payload, provided_sig = parts
    if not b64_payload or not provided_sig:
        return None

    expected_sig = hmac.new(
        _get_signing_secret(), b64_payload.encode("ascii"), hashlib.sha256
    ).hexdigest()
    if not hmac.compare_digest(expected_sig, provided_sig):
        return None

    try:
        padding = "=" * (-len(b64_payload) % 4)
        decoded_bytes = base64.urlsafe_b64decode((b64_payload + padding).encode("ascii"))
        payload = json.loads(decoded_bytes.decode("utf-8"))
        if not isinstance(payload, dict):
            return None
        exp = int(payload.get("exp") or 0)
        now_ts = int(datetime.now(timezone.utc).timestamp())
        if (payload.get("iss") != "safepath" or payload.get("aud") != "safepath-api"
                or exp <= now_ts or not payload.get("sub")
                or int(payload.get("iat", 0)) > now_ts + 30):
            return None
        return payload
    except Exception:
        return None


def verify_proxy_identity_signature(
    email: str,
    provider_account_id: str,
    timestamp_str: str,
    signature: str,
    max_skew_seconds: int = 300,
) -> bool:
    """
    Verifies an HMAC-SHA256 signature generated by the trusted Next.js server-side proxy
    using the shared AUTH_SECRET.
    Message format: "{email}:{provider_account_id}:{timestamp_str}"
    """
    if not email or not signature or not signature.isascii() or not timestamp_str:
        return False
    try:
        ts = int(timestamp_str)
        now_ts = int(datetime.now(timezone.utc).timestamp())
        if abs(now_ts - ts) > max_skew_seconds:
            return False
    except ValueError:
        return False

    msg = f"{email.lower().strip()}:{provider_account_id.strip()}:{timestamp_str.strip()}".encode("utf-8")
    expected_sig = hmac.new(_get_signing_secret(), msg, hashlib.sha256).hexdigest()
    return hmac.compare_digest(expected_sig, signature.strip())
